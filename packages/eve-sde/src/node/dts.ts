import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { basename, dirname, join, relative } from 'node:path'

import { generateTableTypes, type JsonSchema } from '../codegen/json-schema-to-ts'
import { SdeError, SdeHttpError } from '../core/errors'
import { request, requestOk, type FetchFn } from '../core/http'
import { sdeTenantUrl } from '../core/manifest'
import { sdeBlobUrl } from './blob-store'
import type { ResolvedConfig } from './config'
import type { Lockfile } from './lockfile'

const packageName = '@eve-online-tools/eve-sde'

const readJson = async <T>(path: string): Promise<T | undefined> => {
  try {
    return JSON.parse(await readFile(path, 'utf8')) as T
  } catch {
    return undefined
  }
}

/** Record schema of a locked table, cached by table version. Schemas are stored as blobs that outlive the release. */
const loadSchema = async (fetchFn: FetchFn, config: ResolvedConfig, lock: Lockfile, table: string) => {
  const { version } = lock.tables[table]!
  const cachePath = join(config.cacheDir, 'schemas', `${version}.schema.json`)
  const cached = await readJson<JsonSchema>(cachePath)
  if (cached) {
    return cached
  }
  const blob = await request(fetchFn, `${sdeBlobUrl}${version}.schema.json`).catch((error: unknown) => {
    if (error instanceof SdeHttpError && error.status === 403) {
      return undefined
    }
    throw error
  })
  const response = blob ?? (await requestOk(fetchFn, `${sdeTenantUrl}${lock.release}/${table}.schema.json`))
  const schema = (await response.json()) as JsonSchema
  await mkdir(dirname(cachePath), { recursive: true })
  await writeFile(cachePath, JSON.stringify(schema))
  return schema
}

/** `src/eve-sde.d.ts` -> `src/eve-sde.datasets.d.ts` */
export const datasetsDtsPath = (dts: string): string =>
  join(dirname(dts), `${basename(dts).replace(/\.d\.ts$|\.ts$/, '')}.datasets.d.ts`)

const importPath = (from: string, to: string): string => {
  const path = relative(dirname(from), to)
    .split('\\')
    .join('/')
    .replace(/\.(m?ts|m?js)$/, '')
  return path.startsWith('.') ? path : `./${path}`
}

// Ambient module declarations must live in a file without imports or exports, so they are kept apart from the row types.
const datasetDeclarations = (config: ResolvedConfig, path: string): string => {
  // Only registered datasets: dependencies are internal to the datasets that use them.
  const ids = config.datasets.map((dataset) => dataset.id)
  const valueType = (id: string): string =>
    config.configFile
      ? `import(${JSON.stringify(packageName)}).DatasetValue<Extract<NonNullable<typeof import(${JSON.stringify(importPath(path, config.configFile))}).default.datasets>[number], { id: ${JSON.stringify(id)} }>>`
      : 'unknown'
  return [
    '// Generated by the eve-sde plugin. Do not edit.',
    ...ids.map(
      (id) =>
        `declare module ${JSON.stringify(`eve-sde:dataset/${id}`)} {\n  const value: ${valueType(id)}\n  export default value\n}`,
    ),
  ].join('\n\n')
}

const schemaConcurrency = 8

const mapLimited = async <T, R>(items: T[], limit: number, map: (item: T) => Promise<R>): Promise<R[]> => {
  const results: R[] = []
  let next = 0
  const worker = async (): Promise<void> => {
    while (next < items.length) {
      const index = next++
      results[index] = await map(items[index]!)
    }
  }
  await Promise.all(Array.from({ length: Math.min(limit, items.length) }, worker))
  return results
}

// Unchanged declaration files keep their mtime, so tsc and file watchers stay idle.
const writeIfChanged = async (path: string, content: string): Promise<void> => {
  const current = await readFile(path, 'utf8').catch(() => undefined)
  if (current !== content) {
    await writeFile(path, content)
  }
}

/** Writes row types for the locked release to `config.dts` and dataset module types next to it. */
export const writeDts = async (config: ResolvedConfig, lock: Lockfile, fetchFn: FetchFn = globalThis.fetch) => {
  if (!config.dts) {
    throw new SdeError('Set `dts` in the eve-sde config to the declaration file to write.')
  }
  const tables = await mapLimited(Object.keys(lock.tables), schemaConcurrency, async (table) => ({
    table,
    schema: await loadSchema(fetchFn, config, lock, table),
  }))
  const rows = generateTableTypes(tables, {
    augmentModule: packageName,
    header: `// Generated by eve-sde for SDE release ${lock.release}. Do not edit.`,
  })
  const datasetsPath = datasetsDtsPath(config.dts)
  await mkdir(dirname(config.dts), { recursive: true })
  await writeIfChanged(config.dts, `${rows}\n`)
  await writeIfChanged(datasetsPath, `${datasetDeclarations(config, datasetsPath)}\n`)
  return { rows: config.dts, datasets: datasetsPath }
}
