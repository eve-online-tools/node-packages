import { generateTableTypes, type JsonSchema, type TableSchema } from './json-schema-to-ts'

const draft = 'https://json-schema.org/draft/2020-12/schema'
const int: JsonSchema = { type: 'integer', format: 'int32' }
const str: JsonSchema = { type: 'string' }

const localized: JsonSchema = {
  type: 'object',
  properties: { de: str, en: str },
  required: ['en'],
  additionalProperties: false,
}

const table = (name: string, schema: Partial<JsonSchema>): TableSchema => ({
  table: name,
  schema: { $schema: draft, type: 'object', additionalProperties: false, ...schema },
})

const generate = (...tables: TableSchema[]) => generateTableTypes(tables)

describe('generateTableTypes', () => {
  it('emits header, row, registry and key map', () => {
    const output = generate(
      table('types', {
        'x-sde-key': 'typeID',
        properties: { name: str, typeID: int, volume: { type: 'number', format: 'double' } },
        required: ['typeID', 'name'],
      }),
    )
    expect(output).toBe(
      [
        '// Generated by scripts/generate-types.ts from the SDE record schemas. Do not edit.',
        'export type TypesRow = {\n  typeID: number\n  name: string\n  volume?: number\n}',
        'export interface SdeTables {\n  types: { row: TypesRow; key: number }\n}',
        'export const sdeTableKeys = {\n  types: "typeID",\n} as const',
      ].join('\n\n'),
    )
  })

  it('names underscore tables with a Meta prefix and derives string and int64 keys', () => {
    const output = generate(
      table('_sde', { 'x-sde-key': 'key', properties: { key: str }, required: ['key'] }),
      table('_schemaChangelog', {
        'x-sde-key': 'id',
        properties: { id: { type: 'integer', format: 'int64' } },
        required: ['id'],
      }),
    )
    expect(output).toContain('export type MetaSdeRow = {')
    expect(output).toContain('  _sde: { row: MetaSdeRow; key: string }')
    expect(output).toContain('  _schemaChangelog: { row: MetaSchemaChangelogRow; key: number }')
    expect(output).toContain('  _sde: "key",')
  })

  it('sorts tables so input order does not matter', () => {
    const a = table('a', { 'x-sde-key': 'id', properties: { id: int }, required: ['id'] })
    const b = table('b', { 'x-sde-key': 'id', properties: { id: int }, required: ['id'] })
    expect(generate(b, a)).toBe(generate(a, b))
  })

  it('renders enums, arrays and nested objects', () => {
    const output = generate(
      table('things', {
        'x-sde-key': 'id',
        properties: {
          id: int,
          size: { type: 'string', enum: ['S', 'M'] },
          kind: { type: 'integer', format: 'int32', enum: [-1, 0], 'x-enum-varnames': ['none', 'some'] },
          sizes: { type: 'array', items: { type: 'string', enum: ['S', 'M'] } },
          matrix: { type: 'array', items: { type: 'array', items: int } },
          nested: {
            type: 'object',
            properties: { x: { type: 'number', format: 'double' }, flag: { type: 'boolean' } },
            required: ['x'],
            additionalProperties: false,
          },
        },
        required: ['id', 'size'],
      }),
    )
    expect(output).toContain(
      [
        'export type ThingsRow = {',
        '  id: number',
        '  size: "S" | "M"',
        '  kind?: -1 | 0',
        '  sizes?: ("S" | "M")[]',
        '  matrix?: number[][]',
        '  nested?: {',
        '    x: number',
        '    flag?: boolean',
        '  }',
        '}',
      ].join('\n'),
    )
  })

  it('emits identical $defs once and puts keyed def properties first', () => {
    const skill: JsonSchema = {
      'x-sde-key': 'typeID',
      type: 'object',
      properties: { level: int, typeID: int },
      required: ['typeID', 'level'],
      additionalProperties: false,
    }
    const output = generate(
      table('a', {
        'x-sde-key': 'id',
        properties: { id: int, name: { $ref: '#/$defs/Localized' } },
        required: ['id'],
        $defs: { Localized: localized },
      }),
      table('b', {
        'x-sde-key': 'id',
        properties: { id: int, skills: { type: 'array', items: { $ref: '#/$defs/Skill' } } },
        required: ['id'],
        $defs: { Localized: localized, Skill: skill },
      }),
    )
    expect(output.match(/export type Localized =/g)).toHaveLength(1)
    expect(output).toContain('export type Localized = {\n  de?: string\n  en: string\n}')
    expect(output).toContain('export type Skill = {\n  typeID: number\n  level: number\n}')
    expect(output).toContain('  name?: Localized')
    expect(output).toContain('  skills?: Skill[]')
  })

  it('prefixes $defs whose shape differs between tables, including via nested $refs', () => {
    const wrapper: JsonSchema = {
      type: 'object',
      properties: { inner: { $ref: '#/$defs/Inner' } },
      required: ['inner'],
      additionalProperties: false,
    }
    const inner = (properties: Record<string, JsonSchema>): JsonSchema => ({
      type: 'object',
      properties,
      required: [],
      additionalProperties: false,
    })
    const withDefs = (name: string, innerDef: JsonSchema) =>
      table(name, {
        'x-sde-key': 'id',
        properties: { id: int, wrapper: { $ref: '#/$defs/Wrapper' } },
        required: ['id'],
        $defs: { Inner: innerDef, Wrapper: wrapper },
      })
    const output = generate(withDefs('fooBar', inner({ a: int })), withDefs('baz', inner({ b: str })))
    expect(output).toContain('export type FooBarInner = {\n  a?: number\n}')
    expect(output).toContain('export type BazInner = {\n  b?: string\n}')
    expect(output).toContain('export type FooBarWrapper = {\n  inner: FooBarInner\n}')
    expect(output).toContain('export type BazWrapper = {\n  inner: BazInner\n}')
    expect(output).not.toMatch(/export type (Inner|Wrapper) =/)
  })

  it('prefixes $defs named like globals', () => {
    const output = generate(
      table('jobs', {
        'x-sde-key': 'id',
        properties: { id: int, flag: { $ref: '#/$defs/Boolean' } },
        required: ['id'],
        $defs: { Boolean: localized },
      }),
    )
    expect(output).toContain('export type JobsBoolean = {')
    expect(output).toContain('  flag?: JobsBoolean')
  })

  it('throws on generated name collisions', () => {
    const output = () =>
      generate(
        table('types', {
          'x-sde-key': 'id',
          properties: { id: int },
          required: ['id'],
          $defs: { TypesRow: localized },
        }),
      )
    expect(output).toThrow('Generated type name collision: TypesRow')
  })

  it.each<[string, Partial<JsonSchema>, string]>([
    ['oneOf', { properties: { id: int, x: { oneOf: [int, str] } as JsonSchema } }, 'keyword "oneOf"'],
    ['const', { properties: { id: int, x: { type: 'string', const: 'a' } as JsonSchema } }, 'keyword "const"'],
    [
      'map objects',
      { properties: { id: int, x: { type: 'object', additionalProperties: true } } },
      'additionalProperties',
    ],
    [
      'unknown format',
      { properties: { id: int, x: { type: 'integer', format: 'uint8' } } },
      'format "uint8" on integer',
    ],
    ['type arrays', { properties: { id: int, x: { type: ['string', 'null'] } as unknown as JsonSchema } }, 'type'],
    ['missing $ref target', { properties: { id: int, x: { $ref: '#/$defs/Nope' } } }, 'missing definition Nope'],
    ['missing key', { 'x-sde-key': 'nope', properties: { id: int } }, 'x-sde-key nope'],
  ])('throws on %s', (_, schema, message) => {
    const run = () => generate(table('t', { 'x-sde-key': 'id', required: ['id'], ...schema }))
    expect(run).toThrow(message)
  })

  it('throws on recursive $defs', () => {
    const node: JsonSchema = {
      type: 'object',
      properties: { child: { $ref: '#/$defs/Node' } },
      required: [],
      additionalProperties: false,
    }
    const run = () =>
      generate(table('t', { 'x-sde-key': 'id', properties: { id: int }, required: ['id'], $defs: { Node: node } }))
    expect(run).toThrow('Recursive $defs')
  })
})

describe('generateTableTypes for a project', () => {
  it('augments the package registry instead of exporting runtime values', () => {
    const output = generateTableTypes(
      [
        {
          table: 'races',
          schema: {
            $schema: 'https://json-schema.org/draft/2020-12/schema',
            'x-sde-key': 'raceID',
            type: 'object',
            additionalProperties: false,
            required: ['raceID'],
            properties: { raceID: { type: 'integer', format: 'int32' } },
          },
        },
      ],
      { augmentModule: '@eve-online-tools/eve-sde', header: '// project' },
    )
    expect(output).not.toContain('sdeTableKeys')
    expect(output).toContain(
      'declare module "@eve-online-tools/eve-sde" {\n  interface SdeTypeRegistry {\n    tables: SdeTables\n  }\n}',
    )
  })
})
